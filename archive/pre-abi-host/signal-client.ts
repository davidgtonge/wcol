import { asError, decodeFrame, encodeFrame, MAX_PAYLOAD_BYTES, parseControl, validEdge,
  type ClientControl } from "./signal-wire.ts";

interface Deferred<T> {
  promise: Promise<T>;
  resolve(value: T): void;
  reject(error: Error): void;
}

function deferred<T>(): Deferred<T> {
  let resolve!: (value: T) => void;
  let reject!: (error: Error) => void;
  const promise = new Promise<T>((res, rej) => { resolve = res; reject = rej; });
  void promise.catch(() => {});
  return { promise, resolve, reject };
}

async function within<T>(promise: Promise<T>, ms: number, what: string): Promise<T> {
  let timer: ReturnType<typeof setTimeout> | undefined;
  try {
    return await Promise.race([
      promise,
      new Promise<T>((_, reject) => { timer = setTimeout(() => reject(new Error(`${what} timed out`)), ms); }),
    ]);
  } finally {
    if (timer) clearTimeout(timer);
  }
}

interface Receiver {
  controller?: ReadableStreamDefaultController<Uint8Array>;
  queue: Uint8Array[];
  bufferedBytes: number;
  demand: boolean;
  ended: boolean;
}

interface Publisher {
  ready: Deferred<void>;
  finished: Deferred<void>;
  controller?: WritableStreamDefaultController;
}

export interface SignalClientOptions {
  /** e.g. wss://router.example.com/q/query-123/ws */
  url: string;
  /** Per-task signed capability generated by the trusted coordinator. */
  ticket: string;
  createSocket?: (url: string) => WebSocket | Promise<WebSocket>;
  connectTimeoutMs?: number;
  readyTimeoutMs?: number;
  finishTimeoutMs?: number;
  maxQueuedSignalBytes?: number;
  maxSocketBufferBytes?: number;
  heartbeatMs?: number;
}

/**
 * Multiplexed edge signal streams over ONE outbound WebSocket per task.
 * Drop-in input/output streams for chunkReadable / chunkWritable.
 */
export class SignalClient {
  private readonly registered = deferred<void>();
  private readonly readers = new Map<string, Receiver>();
  private readonly writers = new Map<string, Publisher>();
  private readonly options: Required<Pick<SignalClientOptions,
    "readyTimeoutMs" | "finishTimeoutMs" | "maxQueuedSignalBytes" | "maxSocketBufferBytes">>;
  private heartbeat?: ReturnType<typeof setInterval>;
  private failed?: Error;

  private constructor(private readonly socket: WebSocket, config: SignalClientOptions) {
    this.options = {
      readyTimeoutMs: config.readyTimeoutMs ?? 30_000,
      finishTimeoutMs: config.finishTimeoutMs ?? 15_000,
      maxQueuedSignalBytes: config.maxQueuedSignalBytes ?? 2 * 1024 * 1024,
      maxSocketBufferBytes: config.maxSocketBufferBytes ?? 2 * 1024 * 1024,
    };
    socket.binaryType = "arraybuffer";
    socket.addEventListener("message", (event) => this.message(event.data));
    socket.addEventListener("close", () => this.fail(new Error("Signal router connection closed")));
    socket.addEventListener("error", () => this.fail(new Error("Signal router WebSocket error")));

    if ((config.heartbeatMs ?? 0) > 0) {
      this.heartbeat = setInterval(() => {
        if (socket.readyState === WebSocket.OPEN) socket.send("ping");
      }, config.heartbeatMs);
    }
  }

  static async connect(config: SignalClientOptions): Promise<SignalClient> {
    const url = new URL(config.url);
    if (url.protocol !== "wss:" && url.protocol !== "ws:" && url.protocol !== "https:" && url.protocol !== "http:") {
      throw new Error("Signal router URL must use ws(s) or http(s) for Durable Object fetch");
    }
    url.searchParams.set("ticket", config.ticket);
    const created = config.createSocket
      ? config.createSocket(url.toString())
      : new WebSocket(url.toString());
    const socket = await created;
    const client = new SignalClient(socket, config);
    try {
      await within(client.registered.promise, config.connectTimeoutMs ?? 15_000, "WebSocket registration");
      return client;
    } catch (error) {
      client.close();
      throw error;
    }
  }

  /** A consumer's incoming signal bytes. Subscribing makes the publisher writable. */
  readable(edge: string): ReadableStream<Uint8Array> {
    if (!validEdge(edge) || this.readers.has(edge)) throw new Error(`Invalid/duplicate reader: ${edge}`);
    if (this.failed) throw this.failed;
    const state: Receiver = { queue: [], bufferedBytes: 0, demand: false, ended: false };
    this.readers.set(edge, state);
    return new ReadableStream<Uint8Array>({
      start: (controller) => {
        state.controller = controller;
        this.send({ type: "subscribe", edge });
      },
      pull: () => { state.demand = true; this.drain(edge, state); },
      cancel: () => {
        this.readers.delete(edge);
        state.queue.length = 0;
        this.trySend({ type: "unsubscribe", edge });
      },
    }, { highWaterMark: 0 });
  }

  /** A producer's outgoing signal bytes. First write waits for a subscribed consumer. */
  writable(edge: string): WritableStream<Uint8Array> {
    if (!validEdge(edge) || this.writers.has(edge)) throw new Error(`Invalid/duplicate writer: ${edge}`);
    if (this.failed) throw this.failed;
    const state: Publisher = { ready: deferred<void>(), finished: deferred<void>() };
    this.writers.set(edge, state);
    return new WritableStream<Uint8Array>({
      start: (controller) => {
        state.controller = controller;
        this.send({ type: "publish", edge });
      },
      write: async (chunk) => {
        if (!(chunk instanceof Uint8Array)) throw new TypeError("Expected Uint8Array");
        await within(state.ready.promise, this.options.readyTimeoutMs, `Subscriber ${edge}`);
        for (let i = 0; i < chunk.byteLength; i += MAX_PAYLOAD_BYTES) {
          await this.socketCapacity();
          this.socket.send(encodeFrame(edge, chunk.subarray(i, i + MAX_PAYLOAD_BYTES)));
        }
      },
      close: async () => {
        await within(state.ready.promise, this.options.readyTimeoutMs, `Subscriber ${edge}`);
        this.send({ type: "finish", edge });
        await within(state.finished.promise, this.options.finishTimeoutMs, `FIN for ${edge}`);
        this.writers.delete(edge);
      },
      abort: (reason) => {
        this.trySend({ type: "abort", edge, reason: String(reason ?? "Aborted").slice(0, 256) });
        this.writers.delete(edge);
      },
    });
  }

  close(): void {
    this.fail(new Error("Signal client closed"));
    if (this.socket.readyState === WebSocket.CONNECTING || this.socket.readyState === WebSocket.OPEN) {
      this.socket.close(1000, "Done");
    }
  }

  private send(message: ClientControl): void {
    if (this.failed) throw this.failed;
    if (this.socket.readyState !== WebSocket.OPEN) throw new Error("WebSocket is not connected");
    this.socket.send(JSON.stringify(message));
  }

  private trySend(message: ClientControl): void {
    try { this.send(message); } catch { /* A disconnected peer will be retried by the coordinator. */ }
  }

  private async socketCapacity(): Promise<void> {
    while (this.socket.bufferedAmount > this.options.maxSocketBufferBytes) {
      if (this.failed) throw this.failed;
      await new Promise<void>((resolve) => setTimeout(resolve, 5));
    }
    if (this.failed) throw this.failed;
  }

  private message(raw: unknown): void {
    if (this.failed) return;
    try {
      if (raw === "pong") return;
      if (typeof raw === "string") {
        const msg = parseControl(raw);
        switch (msg.type) {
          case "registered": this.registered.resolve(); break;
          case "ready": this.writers.get(msg.edge)?.ready.resolve(); break;
          case "finished": this.writers.get(msg.edge)?.finished.resolve(); break;
          case "end": {
            const state = this.readers.get(msg.edge);
            if (state) { state.ended = true; this.drain(msg.edge, state); }
            break;
          }
          case "error": {
            const error = new Error(`Edge ${msg.edge}: ${msg.reason}`);
            const writer = this.writers.get(msg.edge);
            if (writer) {
              writer.ready.reject(error);
              writer.finished.reject(error);
              writer.controller?.error(error);
            }
            this.errorReader(msg.edge, error);
            break;
          }
          case "subscribed": break;
          default: throw new Error("Unexpected client-only control type");
        }
      } else if (raw instanceof ArrayBuffer || raw instanceof Uint8Array) {
        const { edge, bytes } = decodeFrame(raw);
        const state = this.readers.get(edge);
        if (!state || state.ended) throw new Error(`Unexpected signal bytes for ${edge}`);
        if (state.bufferedBytes + bytes.byteLength > this.options.maxQueuedSignalBytes) {
          this.errorReader(edge, new Error(`Signal queue exceeded limit: ${edge}`));
          this.trySend({ type: "unsubscribe", edge });
          return;
        }
        state.queue.push(bytes);
        state.bufferedBytes += bytes.byteLength;
        this.drain(edge, state);
      } else {
        throw new Error("Unsupported WebSocket message type");
      }
    } catch (error) {
      this.fail(asError(error));
      this.socket.close(1002, "Protocol error");
    }
  }

  private drain(edge: string, state: Receiver): void {
    if (state.demand && state.queue.length > 0) {
      const bytes = state.queue.shift()!;
      state.bufferedBytes -= bytes.byteLength;
      state.demand = false;
      state.controller?.enqueue(bytes);
    }
    if (state.ended && state.queue.length === 0) {
      state.controller?.close();
      this.readers.delete(edge);
    }
  }

  private errorReader(edge: string, error: Error): void {
    const state = this.readers.get(edge);
    if (!state) return;
    this.readers.delete(edge);
    state.queue.length = 0;
    state.controller?.error(error);
  }

  private fail(error: Error): void {
    if (this.failed) return;
    this.failed = error;
    if (this.heartbeat) clearInterval(this.heartbeat);
    this.registered.reject(error);
    for (const [edge] of this.readers) this.errorReader(edge, error);
    for (const publisher of this.writers.values()) {
      publisher.ready.reject(error);
      publisher.finished.reject(error);
      publisher.controller?.error(error);
    }
    this.writers.clear();
  }
}
